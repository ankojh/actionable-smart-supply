-- Search owner rights are isolated to this dedicated single-company service.
-- Do not index the handoff, research prose, hidden events or evaluator schema.
GRANT CREATE CORTEX SEARCH SERVICE ON SCHEMA {{DATABASE}}.{{SCHEMA}} TO ROLE PROJECT_RECOVERY_OWNER_V1;
GRANT SELECT ON TABLE {{DATABASE}}.{{SCHEMA}}.SNAPSHOTS TO ROLE PROJECT_RECOVERY_OWNER_V1;
GRANT SELECT ON TABLE {{DATABASE}}.{{SCHEMA}}.SNAPSHOT_MEMBERS TO ROLE PROJECT_RECOVERY_OWNER_V1;
GRANT SELECT ON TABLE {{DATABASE}}.{{SCHEMA}}.EVIDENCE_DOCUMENTS TO ROLE PROJECT_RECOVERY_OWNER_V1;
-- Change tracking must be enabled by the table owner before the isolated service role builds its index.
ALTER TABLE {{DATABASE}}.{{SCHEMA}}.SNAPSHOTS SET CHANGE_TRACKING=TRUE;
ALTER TABLE {{DATABASE}}.{{SCHEMA}}.SNAPSHOT_MEMBERS SET CHANGE_TRACKING=TRUE;
ALTER TABLE {{DATABASE}}.{{SCHEMA}}.EVIDENCE_DOCUMENTS SET CHANGE_TRACKING=TRUE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE PROJECT_RECOVERY_OWNER_V1;
USE ROLE PROJECT_RECOVERY_OWNER_V1;
CREATE CORTEX SEARCH SERVICE IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.EVIDENCE_SEARCH
 ON TEXT ATTRIBUTES COMPANY,SCOPE,SCHEMA_VERSION,AVAILABLE_AT,SNAPSHOT_ID
 WAREHOUSE={{WAREHOUSE}} TARGET_LAG='1 hour'
 AS SELECT D.DOCUMENT_ID,D.TEXT,D.SHA256,D.COMPANY,D.SCOPE,D.SCHEMA_VERSION,D.AVAILABLE_AT,M.SNAPSHOT_ID
 FROM {{DATABASE}}.{{SCHEMA}}.EVIDENCE_DOCUMENTS D
 JOIN {{DATABASE}}.{{SCHEMA}}.SNAPSHOT_MEMBERS M ON D.DOCUMENT_ID=M.DOCUMENT_ID
  AND D.SHA256=M.SOURCE_SHA256 AND D.COMPANY=M.COMPANY AND D.SCOPE=M.SCOPE AND D.SCHEMA_VERSION=M.SCHEMA_VERSION
 JOIN {{DATABASE}}.{{SCHEMA}}.SNAPSHOTS S ON M.SNAPSHOT_ID=S.SNAPSHOT_ID
  AND M.COMPANY=S.COMPANY AND M.SCOPE=S.SCOPE AND M.SCHEMA_VERSION=S.SCHEMA_VERSION
 WHERE D.COMPANY='synthetic-company' AND D.SCOPE='shortage-recovery-v1'
  AND D.SCHEMA_VERSION='recovery-v1' AND S.STATUS='PUBLISHED'
  AND D.AVAILABLE_AT<=S.AS_OF AND D.TRUSTED=TRUE
  AND D.SOURCE_KIND IN ('synthetic_source','supplier_confirmation','operational_record');
GRANT USAGE ON CORTEX SEARCH SERVICE {{DATABASE}}.{{SCHEMA}}.EVIDENCE_SEARCH TO ROLE PROJECT_RECOVERY_APP_V1;
