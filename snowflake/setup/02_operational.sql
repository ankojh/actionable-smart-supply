-- Versioned operational sources; payloads preserve exact source fidelity.
-- Fixed company/scope views are defense in depth; platform binds exact snapshot/time too.
CREATE TABLE IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.INVENTORY (
 COMPANY VARCHAR NOT NULL,SCOPE VARCHAR NOT NULL,SCHEMA_VERSION VARCHAR NOT NULL,SNAPSHOT_ID VARCHAR NOT NULL,
 SOURCE_ID VARCHAR NOT NULL,ORDINAL NUMBER NOT NULL,PAYLOAD VARIANT NOT NULL,SHA256 VARCHAR NOT NULL,AVAILABLE_AT TIMESTAMP_NTZ NOT NULL);
CREATE SECURE VIEW IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.V_INVENTORY AS
 SELECT * FROM {{DATABASE}}.{{SCHEMA}}.INVENTORY WHERE COMPANY='synthetic-company'
 AND SCOPE='shortage-recovery-v1' AND SCHEMA_VERSION='recovery-v1';
GRANT SELECT ON VIEW {{DATABASE}}.{{SCHEMA}}.V_INVENTORY TO ROLE PROJECT_RECOVERY_APP_V1;
