-- Useful investigative aggregate metrics over operational data only.
CREATE SECURE VIEW IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.V_ORDER_ANALYTICS AS
 SELECT O.SNAPSHOT_ID,O.COMPANY,O.SCOPE,O.SCHEMA_VERSION,O.SOURCE_ID AS ORDER_ID,
 O.PAYLOAD:robots::NUMBER AS ROBOTS,O.PAYLOAD:start_date::DATE AS START_DATE,
 O.PAYLOAD:promised_ship_date::DATE AS PROMISED_SHIP_DATE,
 O.PAYLOAD:contracted::BOOLEAN AS CONTRACTED,S.AS_OF,
 C.PAYLOAD:drivers_per_robot::NUMBER AS DRIVERS_PER_ROBOT,
 O.PAYLOAD:robots::NUMBER*C.PAYLOAD:drivers_per_robot::NUMBER AS REQUIRED_DRIVERS
 FROM {{DATABASE}}.{{SCHEMA}}.CUSTOMER_ORDERS O
 JOIN {{DATABASE}}.{{SCHEMA}}.SNAPSHOTS S ON S.SNAPSHOT_ID=O.SNAPSHOT_ID AND S.COMPANY=O.COMPANY AND S.SCOPE=O.SCOPE AND S.SCHEMA_VERSION=O.SCHEMA_VERSION
 JOIN {{DATABASE}}.{{SCHEMA}}.PRODUCTION_CAPACITY C ON C.SNAPSHOT_ID=O.SNAPSHOT_ID AND C.COMPANY=O.COMPANY AND C.SCOPE=O.SCOPE AND C.SCHEMA_VERSION=O.SCHEMA_VERSION
 WHERE S.STATUS='PUBLISHED' AND O.COMPANY='synthetic-company' AND O.SCOPE='shortage-recovery-v1'
 AND O.SCHEMA_VERSION='recovery-v1' AND O.AVAILABLE_AT<=S.AS_OF AND C.AVAILABLE_AT<=S.AS_OF;
CREATE SEMANTIC VIEW IF NOT EXISTS {{DATABASE}}.{{SCHEMA}}.RECOVERY_ANALYTICS
 TABLES (orders AS {{DATABASE}}.{{SCHEMA}}.V_ORDER_ANALYTICS PRIMARY KEY(SNAPSHOT_ID,ORDER_ID))
 DIMENSIONS (orders.snapshot_id AS SNAPSHOT_ID,orders.company AS COMPANY,orders.scope AS SCOPE,
 orders.schema_version AS SCHEMA_VERSION,orders.order_id AS ORDER_ID,orders.start_date AS START_DATE,
 orders.promised_ship_date AS PROMISED_SHIP_DATE,orders.as_of AS AS_OF,orders.contracted AS CONTRACTED)
 METRICS (orders.total_robots AS SUM(ROBOTS),orders.required_drivers AS SUM(REQUIRED_DRIVERS),orders.order_count AS COUNT(ORDER_ID))
 COMMENT='Synthetic read-only production demand. Always filter exact company, scope, schema_version and snapshot_id. No purchasing authority or feasibility decisions.';
GRANT SELECT ON VIEW {{DATABASE}}.{{SCHEMA}}.V_ORDER_ANALYTICS TO ROLE PROJECT_RECOVERY_APP_V1;
GRANT SELECT,REFERENCES ON SEMANTIC VIEW {{DATABASE}}.{{SCHEMA}}.RECOVERY_ANALYTICS TO ROLE PROJECT_RECOVERY_APP_V1;
